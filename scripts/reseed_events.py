"""
Replace the placeholder incident rows with the real + documented set.

Background
----------
`data/processed/synthetic_events.csv` used to be generated by
`04_build_events.py` with `root_cause = "Synthetic cause for <type>"` and
`mitigation_applied = "Standard mitigation for <type>"`. Every row carried the
same string, so `nlp/extractors.extract_intervention()` matched no rule and fell
through to its default for 100% of events. That CSV has since been rebuilt from
`india_real_events.json` (two cited Indian incidents) plus a paired
cause/response library. This script moves that rebuild into the database.

What it touches, and what it deliberately does not
--------------------------------------------------
The `synthetic_event` table holds three tiers, distinguished by `data_source`:

  synthetic             - generated filler.          REPLACED by this script.
  incident_report_real  - cited Indian incidents.    REPLACED by this script.
  dd_report             - extracted from an uploaded DDR by the real
                          OCR/NLP pipeline.           PRESERVED, never touched.

The `dd_report` rows are pipeline output, not seed data - they are the only
evidence in the database that document ingestion produces structured events, so
they are out of scope here even though they interleave with the others.

Usage (from the repo root):

    ./venv/Scripts/python.exe scripts/reseed_events.py --dry-run
    ./venv/Scripts/python.exe scripts/reseed_events.py
"""

from __future__ import annotations

import argparse
import os
import sys

import pandas as pd

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BACKEND_DIR = os.path.join(REPO_ROOT, "backend")
if BACKEND_DIR not in sys.path:
    sys.path.insert(0, BACKEND_DIR)

from dotenv import load_dotenv  # noqa: E402

load_dotenv(os.path.join(REPO_ROOT, ".env"))

from sqlalchemy import text  # noqa: E402

from database import SessionLocal  # noqa: E402
from models import SyntheticEvent  # noqa: E402

CSV_PATH = os.path.join(REPO_ROOT, "data", "processed", "synthetic_events.csv")
WELLS_PATH = os.path.join(REPO_ROOT, "data", "processed", "wells_master.csv")

# The two tiers this script owns. `dd_report` is intentionally absent.
REPLACED_SOURCES = ("synthetic", "incident_report_real")

MODEL_COLUMNS = {c.name for c in SyntheticEvent.__table__.columns}


def sync_wells(db) -> int:
    """
    Insert any wells present in wells_master.csv but missing from the database.

    Needed because the real incidents reference wells (OIL-BAGHJAN-5,
    OIL-KG-PASARLAPUDI-1) that were added to the CSV for this change; without
    them the event inserts fail the well_master foreign key.
    """
    wells = pd.read_csv(WELLS_PATH)
    existing = {row[0] for row in db.execute(text("SELECT well_id FROM well_master")).all()}

    added = 0
    for row in wells.itertuples(index=False):
        if row.well_id in existing:
            continue
        if pd.isna(row.surface_lat) or pd.isna(row.surface_lon):
            print(f"  SKIP {row.well_id}: no coordinates, cannot build a surface_location")
            continue
        db.execute(
            text(
                """
                INSERT INTO well_master
                    (well_id, field_name, kb_elevation, total_depth_tvd, spud_date, surface_location)
                VALUES
                    (:well_id, :field_name, :kb, :td, :spud,
                     ST_SetSRID(ST_MakePoint(:lon, :lat), 4326))
                ON CONFLICT (well_id) DO NOTHING
                """
            ),
            {
                "well_id": row.well_id,
                "field_name": row.field_name,
                "kb": None if pd.isna(row.kb_elevation) else float(row.kb_elevation),
                "td": None if pd.isna(row.total_depth_tvd) else float(row.total_depth_tvd),
                "spud": None if pd.isna(row.spud_date) else str(row.spud_date),
                "lon": float(row.surface_lon),
                "lat": float(row.surface_lat),
            },
        )
        added += 1
        print(f"  + well {row.well_id}")
    return added


def main() -> int:
    parser = argparse.ArgumentParser(description="Reseed the event table.")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not os.path.exists(CSV_PATH):
        print(f"FAILED: {CSV_PATH} not found. Run scripts/04_build_events.py first.")
        return 1

    frame = pd.read_csv(CSV_PATH)
    frame = frame.replace({float("nan"): None})

    # Keep only real model columns: the CSV carries `event_id` (a human label the
    # table has no column for) and future columns must not break the insert.
    unknown = [c for c in frame.columns if c not in MODEL_COLUMNS]
    records = frame[[c for c in frame.columns if c in MODEL_COLUMNS]].to_dict(orient="records")

    by_source: dict[str, int] = {}
    for rec in records:
        by_source[rec.get("data_source")] = by_source.get(rec.get("data_source"), 0) + 1

    db = SessionLocal()
    try:
        current = dict(
            db.execute(
                text("SELECT data_source, count(*) FROM synthetic_event GROUP BY data_source")
            ).all()
        )

        print("=" * 68)
        print("Event reseed")
        print("=" * 68)
        print(f"  CSV rows        : {len(records)}  {by_source}")
        if unknown:
            print(f"  CSV-only columns: {unknown}  (ignored — no matching table column)")
        print(f"  DB before       : {current}")
        print(f"  replacing tiers : {list(REPLACED_SOURCES)}")
        print(f"  preserving tiers: {[k for k in current if k not in REPLACED_SOURCES]}")
        print("-" * 68)

        if args.dry_run:
            print("  Dry run — nothing written.")
            return 0

        added_wells = sync_wells(db)
        print(f"  wells added     : {added_wells}")

        deleted = db.execute(
            text("DELETE FROM synthetic_event WHERE data_source = ANY(:srcs)"),
            {"srcs": list(REPLACED_SOURCES)},
        ).rowcount
        print(f"  events deleted  : {deleted}")

        db.bulk_insert_mappings(SyntheticEvent, records)
        db.commit()

        after = dict(
            db.execute(
                text("SELECT data_source, count(*) FROM synthetic_event GROUP BY data_source")
            ).all()
        )
        print(f"  DB after        : {after}")
        print("-" * 68)
        print("  New rows have NULL embeddings. Run:")
        print("    ./venv/Scripts/python.exe scripts/backfill_embeddings.py")
        print("  then rebuild the graph:")
        print("    POST /api/graph/rebuild")
        return 0
    except Exception as exc:
        db.rollback()
        print(f"  FAILED (rolled back): {exc}")
        return 1
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())
